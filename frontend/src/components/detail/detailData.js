      duration: '±10 – 16 menit',
      walkToPickup: '±120 meter (2–3 mnt jalan kaki)',
      pickupPoint: 'Tepi jalan raya / Halte pangkalan angkot terdekat',
      instruction: `Dari lokasi Anda, jalan kaki ke jalan raya lalu cegat ${angkotCode}. Konfirmasi ke supir: "Punten Mang, ngalangkung ${name} / ${place?.address ? place.address.split(',')[0] : 'arah sini'}?".`,
