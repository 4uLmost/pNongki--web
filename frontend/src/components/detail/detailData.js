  const isDipatiukur = address.includes('dipatiukur') || address.includes('lebakgede');
  const isRiau = address.includes('riau') || address.includes('martadinata');
  const isGanesha = address.includes('ganesha') || address.includes('itb');

  let angkotCode = 'Angkot No. 02 / 09';
  let angkotColor = 'Warna Hijau - Garis Oranye / Hijau Tua';
  let angkotRouteDesc = 'Trayek Cicaheum - Ciroyom / Dago - St. Hall';

