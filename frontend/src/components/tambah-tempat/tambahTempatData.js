export function getDistrictsByCity(cityName) {
  if (!cityName) return [];
  const normalized = cityName.toLowerCase();
  if (normalized.includes('barat')) {
    return BANDUNG_BARAT_DISTRICTS_MASTER;
  }
  if (normalized.includes('cimahi')) {
    return CIMAHI_DISTRICTS_MASTER;
  }
  if (normalized.includes('kabupaten') && normalized.includes('bandung')) {
    return KAB_BANDUNG_DISTRICTS_MASTER;
  }
  if (normalized.includes('bandung')) {
    return KOTA_BANDUNG_DISTRICTS_MASTER;
  }
  return [];
}

